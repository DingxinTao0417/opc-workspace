test("signed manifest staging preserves existing aliases and has no secret fields", () => {
  const dir = mkdtempSync(join(tmpdir(), "opc-helper-build-test-"));
  try {
    const retained = join(dir, "retained");
    const destination = join(dir, bindingFileName);
    writeFileSync(retained, "keep these bytes");
    linkSync(retained, destination);
    const signer = createBuildSigner();
    const manifest = signer.signPair("ab".repeat(32), "cd".repeat(32));
    stageBuildBinding(destination, manifest, signer.publicHex);
    assert.equal(readFileSync(retained, "utf8"), "keep these bytes");
    assert.deepEqual(JSON.parse(readFileSync(destination)), manifest);
    assert.deepEqual(Object.keys(manifest).sort(), [
      "desktopSha256",
      "helperSha256",
      "signature",
      "version",
    ]);
    assert.equal(
      readdirSync(dir).some((name) => name.startsWith(".opc-binding-stage-")),
      false,
    );
    assert.throws(() =>
      stageBuildBinding(
        destination,
        { ...manifest, version: 2 },
        signer.publicHex,
      ),
    );
    assert.deepEqual(JSON.parse(readFileSync(destination)), manifest);
  } finally {
    assert.equal(dirname(resolve(dir)), resolve(tmpdir()));
    assert.ok(basename(dir).startsWith("opc-helper-build-test-"));
    rmSync(dir, { recursive: true });
  }
});

test("desktop deliverable is detached from Cargo cache aliases before signing", () => {
  const dir = mkdtempSync(join(tmpdir(), "opc-helper-build-test-"));
  try {
    const cache = join(dir, "cached.exe");
    const deliverable = join(dir, "desktop.exe");
    writeFileSync(cache, "original build bytes");
    linkSync(cache, deliverable);
    stageImage(deliverable, deliverable);
    assert.equal(readFileSync(cache, "utf8"), "original build bytes");
    writeFileSync(cache, "next compilation");
    assert.equal(readFileSync(deliverable, "utf8"), "original build bytes");
    assert.equal(
      readdirSync(dir).some((p) => p.startsWith(".opc-helper-stage-")),
      false,
    );
  } finally {
    assert.equal(dirname(resolve(dir)), resolve(tmpdir()));
    assert.ok(basename(dir).startsWith("opc-helper-build-test-"));
    rmSync(dir, { recursive: true });
  }
});
